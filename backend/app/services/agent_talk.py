"""분석 파이프라인이 못 받는 질문에 **그냥 답하는** 층.

왜 필요한가. `/api/agent/ask`는 문장에서 지명을 뽑아 도구를 돌리는 구조다. 지명이
없거나 좌표를 못 찾으면 종전엔 400과 함께 한 문장으로 끝났다:

    "'…'에서 분석할 위치를 찾지 못했어요. 지금은 서울 안의 지역만 …"

그런데 사용자가 그 자리에 넣는 말은 대개 **위치를 빠뜨린 분석 요청이 아니라
다른 종류의 질문**이다 — "공시지가랑 실거래가 뭐가 달라?", "권리금은 어떻게
따져?", "이 서비스로 뭘 알 수 있어?". 거기에 위치를 되묻기만 하면 답이 아니다
(소유자 지적: "얘는 자기가 모르는 걸 못 말하고, 답변의 질이 떨어진다").

그래서 도구 없이 LLM이 직접 답한다. 대신 두 가지를 프롬프트에서 못 하게 막는다:

1. **특정 지역의 수치를 말하지 않는다.** 그건 엔진이 계산하는 값이고, LLM이
   말하면 그 자리에서 지어낸 숫자가 된다. 이 프로젝트의 원칙(숫자는 엔진,
   서술은 LLM)이 여기서도 그대로다.
2. **모르는 것은 모른다고 말한다.** 우리 데이터로 확인되지 않는 것(건물 소유자,
   특정 점포 매출, 서울 밖 지역)은 확인되지 않는다고 분명히 밝힌다.

LLM이 꺼져 있거나 실패하면 None을 돌려준다 — 호출부는 종전 400 안내로 돌아간다.
"""

from __future__ import annotations

import logging

from app.services.llm_client import complete_text, llm_enabled

logger = logging.getLogger(__name__)

# 이 서비스가 실제로 가진 데이터. 프롬프트에 그대로 실어, 할 수 있는 일과 못 하는
# 일을 LLM이 임의로 상상하지 않게 한다. 새 데이터가 붙으면 여기도 고친다.
CAPABILITIES = """이 서비스가 가진 것(서울 한정):
- 도로망 공간구문 지표(Integration·Choice) — 길 구조상 사람이 지나가게 되는 정도
- 생활인구(시간대별, 내국인+단기체류 외국인)·길단위 유동인구(성·연령·요일)·
  거주인구·직장인(행정동/격자 단위), 연령대 구성, 지역 카드 소비
- 인허가 개업·폐업 이력, 상권변화지표, 집객시설, 부동산원 공실률·임대료,
  대규모점포, 최근 건축허가, 정비구역, 지하철 역별 승하차
- 업종별 점포 수와 점포당 매출 추정(골목상권 통계), 프랜차이즈 가맹 현황
- 개별공시지가(전 필지, 2026년), 필지 경계·형상·도로접면
- 아파트·오피스텔 실거래(토지 실거래는 없다), 지하철 승하차
- 판정 도구: 입지 점수, 임차 계약 판정, 매입 판정, 후보지 비교, 매장 진단,
  자리 찾기, 잠식 위험, 도달권, 신설도로 시뮬레이션, 실내 도면 VGA
없는 것:
- 서울 밖 지역 전부
- 토지 실거래가(지번이 마스킹돼 필지에 붙지 않는다), 개별 점포의 실제 매출·임대료
- 건물 소유자·등기·권리관계, 실제 매물 목록과 그 가격
- 특정 브랜드의 내부 매출, 미래 시세 예측"""


async def talk_answer(question: str, *, history_summary: str = "") -> str | None:
    """도구 없이 답한다. LLM이 없거나 실패하면 None."""
    q = (question or "").strip()
    if not q or not llm_enabled():
        return None

    user = q if not history_summary else f"앞 대화 요약: {history_summary}\n\n질문: {q}"
    try:
        text = await complete_text(
            system=(
                # 2026-11-06: 400자·"아는 척하지 않는다" 위주였던 지시를 풀었다. 이 경로로
                # 오는 건 대개 개념·창업 실무 질문인데, 일반 GPT보다 짧고 소극적으로 답했다.
                "너는 한국의 상권·창업 입지 상담가다. 이번 질문은 특정 위치가 없어 분석 "
                "엔진을 돌리지 않았다. 너의 지식으로 충실하게 답한다.\n\n"
                f"{CAPABILITIES}\n\n"
                "규칙:\n"
                "- 질문이 실제로 묻는 것에 첫 문장부터 바로 답한다. 창업 실무, 업계 관행, "
                "제도의 일반론, 체크리스트, 개념 설명은 아는 만큼 구체적으로 쓴다.\n"
                "- 특정 지역·필지의 수치(점수·인구·매출·지가)는 지어내지 않는다. 그게 필요한 "
                "질문이면 일반론으로 답한 뒤, 이 서비스에서 장소를 넣어 물으면 계산해 준다고 "
                "한 줄로 안내한다(예: '신촌역 카페 자리 어때?').\n"
                "- 서울 밖 지역은 우리 데이터에 없다고 밝히되, 일반 지식으로 도울 수 있는 만큼 돕는다.\n"
                "- 형식은 질문에 맞춘다. 간단하면 몇 문장, 절차는 번호 목록, 비교는 표. "
                "소제목이 필요하면 한 줄을 **굵게** 쓴다(# 제목은 쓰지 않는다). 한국어 존댓말."
            ),
            user=user,
            max_tokens=2500,
            timeout_s=25.0,
        )
    except Exception as exc:  # noqa: BLE001 - 폴백이 목적
        logger.warning("talk_answer 실패 — %s", exc)
        return None
    return (text or "").strip() or None
